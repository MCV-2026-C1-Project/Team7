"""Week 4, Task 2 (I): final result tables for the slides, from the outputs of task2_metrics.py and task2_check.py.

1. Descriptor x metric: for each, the ratio / cross-check / score with the best mean known-painting mAP@1 over
   QSD1-W4 and QSD2-W3 (ties: mAP@5, then time).
2. Ablation of the chosen configuration (SIFT, Hellinger, ratio 0.75): ratio test only -> + cross-check -> + RANSAC
   inliers -> + distinct inliers -> + homography plausibility check.
Known paintings only (gt -1 is Task 2 II). Writes weeks/week4/results/task2/task2_table.csv, task2_ablation.csv and
task2_results.md. Usage (from the repository root): python weeks/week4/experiments/task2_tables.py
(no dataset is read; --help only prints this text)
"""
import argparse
import csv
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "weeks" / "week4" / "results" / "task2"
SETS = {"qsd1_w4": "QSD1-W4", "qsd2_w3": "QSD2-W3"}
KEY = ("descriptor", "metric", "ratio", "cross_check", "score")


def read(path: Path) -> list[dict]:
    with open(path, encoding="utf-8") as f:
        return list(csv.DictReader(f))


def known_metrics(name: str) -> dict[tuple, dict]:
    """Per configuration: known-painting top-1, mAP@1, mAP@5 (from the per-painting ranks) and seconds per query."""
    seconds = {tuple(r[k] for k in KEY): float(r["sec_per_query"]) for r in read(OUT / f"metrics_{name}.csv")}
    groups: dict[tuple, list[dict]] = {}
    for r in read(OUT / f"metrics_{name}_paintings.csv"):
        if r["gt"] not in ("-1", ""):
            groups.setdefault(tuple(r[k] for k in KEY), []).append(r)
    out = {}
    for key, rows in groups.items():
        ranks = [int(r["rank_in_top10"]) if r["rank_in_top10"] else None for r in rows]
        out[key] = {"top1": f"{sum(r == 1 for r in ranks)}/{len(ranks)}",
                    "map1": statistics.mean(r == 1 for r in ranks),
                    "map5": statistics.mean(1 / r if r and r <= 5 else 0 for r in ranks), "sec": seconds[key]}
    return out


def main() -> None:
    metrics = {name: known_metrics(name) for name in SETS}
    keys = sorted(metrics["qsd1_w4"])
    rank = lambda k: (statistics.mean(metrics[n][k]["map1"] for n in SETS), statistics.mean(metrics[n][k]["map5"] for n in SETS),
                      -statistics.mean(metrics[n][k]["sec"] for n in SETS))
    table = []
    for pair in dict.fromkeys(k[:2] for k in keys):
        best = max((k for k in keys if k[:2] == pair), key=rank)
        row = dict(zip(KEY, best))
        for name, label in SETS.items():
            m = metrics[name][best]
            row |= {f"{label} top-1": m["top1"], f"{label} mAP@1": round(m["map1"], 3), f"{label} mAP@5": round(m["map5"], 3),
                    f"{label} s/query": round(m["sec"], 1)}
        table.append(row)
    steps = [("ratio test only", ("SIFT", "Hellinger", "0.75", "off", "matches")),
             ("+ cross-check", ("SIFT", "Hellinger", "0.75", "on", "matches")),
             ("+ RANSAC homography inliers", ("SIFT", "Hellinger", "0.75", "on", "inliers")),
             ("+ distinct inliers (chosen)", ("SIFT", "Hellinger", "0.75", "on", "distinct"))]
    ablation = []
    for label, key in steps:
        row = {"step": label}
        for name, set_label in SETS.items():
            m = metrics[name][key]
            row |= {f"{set_label} top-1": m["top1"], f"{set_label} mAP@1": round(m["map1"], 3),
                    f"{set_label} mAP@5": round(m["map5"], 3), f"{set_label} s/query": round(m["sec"], 1)}
        ablation.append(row)
    check = {r["set"]: r for r in read(OUT / "homography_check.csv") if r["variant"] == "with check"}
    row = {"step": "+ homography plausibility check (not kept)"}
    for name, set_label in SETS.items():
        row |= {f"{set_label} top-1": check[name]["top1_known"], f"{set_label} mAP@1": round(float(check[name]["map1_known"]), 3),
                f"{set_label} mAP@5": round(float(check[name]["map5_known"]), 3), f"{set_label} s/query": ""}
    ablation.append(row)
    for path, rows in ((OUT / "task2_table.csv", table), (OUT / "task2_ablation.csv", ablation)):
        with open(path, "w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0]))
            w.writeheader()
            w.writerows(rows)
    md = ["# Week 4, Task 2 (I): matching results", "",
          "Known paintings only (QSD1-W4: 29 of 39, the 10 unknowns are Task 2 II; QSD2-W3: all 39). Week 3 "
          "segmentation, noise filter and painting order; DoG keypoints, at most 1000 per image, 900 px; top 10 per "
          "painting. Generated by weeks/week4/experiments/task2_tables.py.", "",
          "## Descriptor × metric (best ratio / cross-check / score for each)", "", markdown(table), "",
          "## Ablation of the chosen configuration (SIFT + Hellinger / RootSIFT, ratio 0.75)", "", markdown(ablation), ""]
    (OUT / "task2_results.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))


def markdown(rows: list[dict]) -> str:
    header = list(rows[0])
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(r[h]) for h in header) + " |" for r in rows]
    return "\n".join(lines)


if __name__ == "__main__":
    argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter).parse_args()
    main()
